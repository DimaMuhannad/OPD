function variant(V) {
  const order = V === "A" ? [...MC.keys()] : ORDER_B;
  const pos = V === "A" ? POS_A : POS_B;
  const key = [];
  const kids = [
    p([run("ГУАП · Кафедра № 3 · курс проектной деятельности", { size: 16 })]),
    p([run(`ТЕСТ 1. Инициация проекта · вариант ${V === "A" ? "А" : "Б"}`, { bold: true, size: 28 })], { after: 20 }),
    p("15 минут · без конспектов и телефонов · максимум 30 баллов · зачтено от 15", { size: 18 }),
    p("Фамилия, имя: ______________________________   Группа: __________   Команда: __________", { before: 80, after: 80 }),
    p("Часть 1. Выберите один ответ и обведите букву · по 1 баллу", { bold: true, before: 60 }),
  ];
  order.forEach((qi, n) => {
    const a = arrange(MC[qi].opts, pos[qi]);
    key.push(L[pos[qi]]);
    kids.push(p([run(`${n + 1}. `, { bold: true }), run(MC[qi].q)], { before: 60, after: 20, keepNext: true }));
    a.forEach((o, k) => kids.push(p(`${L[k]}) ${o}`, { indent: { left: 360 }, after: 0, keepNext: k < 3 })));
  });
  // Часть 2
  kids.push(p("Часть 2. Соответствие, несколько ответов, порядок", { bold: true, before: 160 }));
  kids.push(p([run("15. ", { bold: true }), run("Впишите напротив каждой проверки букву SMART (S, M, A, R, T). Каждая буква — один раз.   (5 б)")], { before: 60 }));
  const so = SMART_ORDER[V];
  kids.push(table([["Проверка", "Буква"], ...so.map((i) => [SMART_ROWS[i][0], ""])], [88, 12]));
  kids.push(p([run("16. ", { bold: true }), run("Отметьте ВСЕ источники идей для проекта, которые разбирались на курсе.   (2 б)")], { before: 100 }));
  const io = IDEAS_ORDER[V];
  io.forEach((i, k) => kids.push(p(`☐ ${L.concat(["д", "е"])[k]}) ${IDEAS[i]}`, { indent: { left: 360 }, after: 0 })));
  kids.push(p([run("17. ", { bold: true }), run("Пронумеруйте шаги фазы инициации по порядку, от 1 до 5.   (2 б)")], { before: 100 }));
  const st = STEPS_ORDER[V];
  kids.push(table([["Шаг", "№"], ...st.map((i) => [STEPS[i], ""])], [88, 12]));
  // Часть 3
  kids.push(p("Часть 3. Коротко письменно", { bold: true, before: 160 }));
  kids.push(p([run("18. ", { bold: true }), run("Цель: «Сделать удобное приложение для студентов к концу семестра». Назовите три требования SMART, которые не выполнены, и объясните каждое одной строкой.   (3 б)")], { before: 60 }));
  for (let i = 0; i < 3; i++) kids.push(p("_________________________________________________________________________________", { before: 60 }));
  kids.push(p([run("19. ", { bold: true }), run("Запишите одну границу вашего проекта в форме отказа и укажите тип: чего не делаем / для кого не делаем / чего не гарантируем.   (2 б)")], { before: 100 }));
  for (let i = 0; i < 1; i++) kids.push(p("_________________________________________________________________________________", { before: 60 }));
  kids.push(p([run("20. ", { bold: true }), run("Запишите один критерий успеха вашего проекта так, чтобы его можно было проверить ответом «да» или «нет».   (2 б)")], { before: 100 }));
  for (let i = 0; i < 1; i++) kids.push(p("_________________________________________________________________________________", { before: 60 }));
  const smartKey = so.map((i) => SMART_ROWS[i][1]).join(", ");
  const ideasKey = io.map((i, k) => (IDEAS_OK.includes(i) ? L.concat(["д", "е"])[k] : null)).filter(Boolean).join(", ");
  const stepsKey = st.map((i) => i + 1).join(", ");
  return { kids, key, smartKey, ideasKey, stepsKey };
}

function keySheet(vs) {
  const kids = [
    p([run("ТЕСТ 1 «Инициация» · ЛИСТ ПРЕПОДАВАТЕЛЯ · КЛЮЧ · НЕ РАЗДАВАТЬ", { bold: true, size: 26 })], { after: 80 }),
    p("Максимум 30 баллов · зачтено от 15 · в БРС: результат ÷ 3 · пересдача — один раз, на следующем занятии", { size: 18, after: 120 }),
  ];
  for (const [name, v] of vs) {
    kids.push(p(`Вариант ${name}`, { bold: true, size: 24, before: 120 }));
    const row1 = ["№", ...v.key.map((_, i) => String(i + 1))];
    const row2 = ["Ответ", ...v.key];
    kids.push(table([row1, row2], [10, ...v.key.map(() => 90 / 14)]));
    kids.push(p(`15 — по 1 баллу за строку, сверху вниз: ${v.smartKey}.`, { before: 80 }));
    kids.push(p(`16 — отмечены ровно ${v.ideasKey}: 2 балла; одна ошибка (лишний или пропущенный пункт): 1 балл; две и больше: 0.`));
    kids.push(p(`17 — сверху вниз: ${v.stepsKey}. Полностью верно: 2 балла; одна перестановка двух соседних шагов: 1 балл.`));
  }
  kids.push(p("Часть 3 — одинаково для обоих вариантов", { bold: true, size: 24, before: 160 }));
  kids.push(p("18 — по 1 баллу за требование, названное и объяснённое верно, максимум 3. S: «удобное приложение» — неизвестно, что именно появится. M: нет числа, «удобное» не измеряется. T: «к концу семестра» — не дата. Засчитывать R, если объяснено, что не видна связь с проблемой; A — если объяснено, почему ресурса нет."));
  kids.push(p("19 — 2 балла: граница записана как отказ и тип указан верно. 1 балл: содержание верное, но не в форме отказа («постараемся не…») или тип не указан. 0: это задача, а не граница."));
  kids.push(p("20 — 2 балла: критерий проверяется ответом «да / нет» и содержит проверяемый признак. 1 балл: признак есть, формулировка описательная. 0: это цель, а не критерий."));
  kids.push(p("Ответы 19 и 20 у каждой команды свои: проверяется форма, а не совпадение с образцом. У участников одной команды содержание может совпадать — это не списывание.", { italic: true, before: 60 }));
  return kids;
}

