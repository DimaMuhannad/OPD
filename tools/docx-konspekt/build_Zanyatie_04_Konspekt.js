function run(text, opts = {}) {
  return new TextRun({
    text, font: FONT, color: opts.color || INK, size: opts.size || 20,
    bold: !!opts.bold, italics: !!opts.italic,
  });
}
function mix(parts, opts = {}) {
  // parts: array of [text, {bold,italic}] or plain string
  return parts.map(p => Array.isArray(p) ? run(p[0], { size: opts.size, ...p[1] }) : run(p, opts));
}
function para(children, opts = {}) {
  const kids = Array.isArray(children) ? children : [run(children, opts)];
  return new Paragraph({
    children: kids,
    spacing: { before: opts.before ?? 0, after: opts.after ?? 140, line: 276 },
    shading: opts.shade ? { type: ShadingType.CLEAR, fill: FILL, color: "auto" } : undefined,
    border: opts.shade ? {
      top: { style: BorderStyle.SINGLE, size: 4, color: BORDER, space: 4 },
      bottom: { style: BorderStyle.SINGLE, size: 4, color: BORDER, space: 4 },
      left: { style: BorderStyle.SINGLE, size: 4, color: BORDER, space: 8 },
      right: { style: BorderStyle.SINGLE, size: 4, color: BORDER, space: 8 },
    } : undefined,
  });
}
function callout(label, text, opts = {}) {
  const kids = [run(label + " ", { bold: true, italic: true })];
  kids.push(...(typeof text === "string" ? [run(text, { italic: true })] : text.map(p => Array.isArray(p) ? run(p[0], { italic: true, ...p[1] }) : run(p, { italic: true }))));
  return para(kids, { shade: true, before: 80, after: 160 });
}
function h1(text) {
  return new Paragraph({
    children: [run(text, { bold: true, size: 32 })],
    spacing: { before: 0, after: 160 },
    border: { bottom: { style: BorderStyle.SINGLE, size: 8, color: RULE, space: 6 } },
  });
}
function h2(text) {
  return new Paragraph({
    children: [run(text, { bold: true, size: 26 })],
    spacing: { before: 320, after: 140 },
    border: { bottom: { style: BorderStyle.SINGLE, size: 6, color: RULE, space: 4 } },
  });
}
function h3(text) {
  return new Paragraph({
    children: [run(text, { bold: true, size: 22 })],
    spacing: { before: 220, after: 90 },
  });
}
function bullets(items) {
  return items.map(it => para(
    [run("— ", {}), ...(Array.isArray(it) ? it.map(p => Array.isArray(p) ? run(p[0], p[1]) : run(p)) : [run(it)])],
    { after: 90 }
  ));
}
function numbered(items, opts = {}) {
  return items.map((it, i) => para(
    [run(`${i + 1}. `, { bold: true }), ...(Array.isArray(it) ? it.map(p => Array.isArray(p) ? run(p[0], p[1]) : run(p)) : [run(it)])],
    { after: opts.after ?? 110 }
  ));
}
function toRuns(children, opts = {}) {
  if (typeof children === "string") return [run(children, opts)];
  if (Array.isArray(children)) {
    return children.map(c => {
      if (c instanceof TextRun) return c;
      if (Array.isArray(c)) return run(c[0], { ...opts, ...c[1] });
      return run(c, opts);
    });
  }
  return [children];
}
function cell(children, opts = {}) {
  const kids = toRuns(children, { size: opts.size ?? 18, bold: opts.bold, italic: opts.italic });
  return new TableCell({
    width: { size: opts.width || 0, type: WidthType.PERCENTAGE },
    shading: opts.header ? { type: ShadingType.CLEAR, fill: FILL, color: "auto" } : undefined,
    borders: cellBorders,
    verticalAlign: "center",
    margins: { top: 60, bottom: 60, left: 100, right: 100 },
    children: [new Paragraph({ children: kids, spacing: { after: 0, line: 250 } })],
  });
}
function table(headerRow, rows, widths) {
  const w = widths || headerRow.map(() => Math.floor(100 / headerRow.length));
  return new Table({
    width: { size: 100, type: WidthType.PERCENTAGE },
    rows: [
      new TableRow({
        children: headerRow.map((h, i) => cell(h, { header: true, width: w[i], bold: true, size: 18 })),
      }),
      ...rows.map(r => new TableRow({
        children: r.map((c, i) => cell(c, { width: w[i], size: 18 })),
      })),
    ],
  });
}
function spacer(h = 60) { return new Paragraph({ spacing: { after: h } }); }

