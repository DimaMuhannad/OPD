// Доска занятия 9 «Команда и исполнение» (самостоятельная работа) для команды в Excalidraw.
// Пять зон — те же, что на бланке (tools/docx-konspekt/build_Zanyatie_09_Komanda_A4_Blank.js) и в конспекте:
// кто за что отвечает → командный договор → журнал проекта → план против факта → что покажем на чекпоинте.
// Рамки и подписи закреплены, стикеры двигаются; серые «Пример:» — умный горшок.
// Запуск: node tools/excalidraw/z09_board.js [файл] [команда]  → zanyatiya/Zanyatie_09_Doska.excalidraw
const fs = require("fs");
const { text, rect, sticker, setPrefix } = require("./scene");
setPrefix("z9_");

const W = 1640, L = { locked: true };
const BLUE = "#a5d8ff", RED = "#ffc9c9", ZONE = "#f8f9fa", WHITE = "#ffffff";
const EX = "#868e96";
const ex = (t) => "Пример:\n" + t;
const els = [];
const add = (a) => els.push(...a);
let zoneStart = 0, zoneNo = 0;
const COLW = W + 120, ROWH = 1100;
const zone = (h, title, hint) => {
  zoneStart = els.length;
  add(rect(0, 0, W, h, { backgroundColor: ZONE, strokeColor: "#adb5bd", strokeWidth: 2, ...L }));
  add(text(30, 22, title, 34, { ...L, strokeColor: "#1971c2" }));
  if (hint) add(text(30, 72, hint, 20, { ...L, strokeColor: "#495057" }));
};
const place = () => {
  const dx = (zoneNo % 3) * COLW, dy = Math.floor(zoneNo / 3) * ROWH;
  for (const e of els.slice(zoneStart)) { e.x += dx; e.y += dy; e.customData = { zone: zoneNo + 1 }; }
  zoneNo++;
};
const head = (cols, y) => cols.forEach(([t, x]) => add(text(x, y, t, 19, { ...L, strokeColor: "#1971c2" })));
const cellS = (x, y, w, h, label, isEx, o = {}) => add(sticker(x, y, label, { width: w, height: h, backgroundColor: WHITE, strokeColor: "#adb5bd", ...(isEx ? { tc: EX, size: 15 } : {}), ...o }));

// ── Шапка ──
add(text(0, -150, "Занятие 9 · Команда и исполнение: от плана к делу", 40, L));
const team = process.argv[3] || "______________";
add(text(0, -90, `Команда: ${team}   Проект: ______________________   Двойной щелчок по стикеру — писать; Ctrl+D — копия. Серые «Пример:» — про умный горшок: сотрите и впишите своё`, 20, { ...L, strokeColor: "#495057" }));

// ── 1. Кто за что отвечает ──
zone(1000, "1. Кто за что отвечает",
  "Пакеты ближайших недель: ответственный из WBS и запасной — он в курсе и подхватит. На критическом пути запасной обязателен.");
const C1 = [["Пакет (код и название из WBS)", 30, 760], ["Ответственный", 810, 380], ["Запасной", 1210, 400]];
head(C1, 125);
const ex1 = ["1.2 Схема собрана и проверена на столе", "технический эксперт", "лидер"];
for (let i = 0; i < 6; i++) C1.forEach(([, x, w], j) => cellS(x, 165 + i * 105, w, 92, i === 0 ? ex(ex1[j]) : " ", i === 0));
cellS(30, 810, 760, 90, ex("доводит до конца (доводчик): аналитик"), true);
cellS(810, 810, 800, 90, ex("проверяет «а точно сработает?» (аналитик-критик):\nтехнический эксперт"), true);
add(text(30, 925, "Пакеты критического пути — красным: выделите стикер и смените цвет фона.", 18, { ...L, strokeColor: "#c92a2a" }));
place();

// ── 2. Командный договор ──
zone(1000, "2. Командный договор: пять правил",
  "Пишем до споров, ссылаемся на правило при споре. Правило проверяемое: по нему видно, нарушено оно или нет.");
const Q = [["1. Как держим связь", "где пишем, за сколько отвечаем", "общий чат в Telegram; отвечаем за сутки; срочное — звонок"],
  ["2. Когда сверяемся", "день, время, кто пишет журнал", "воскресенье 20:00, 15 минут; журнал пишет лидер"],
  ["3. Как принимаем решения", "по пакету, по общему, если не договорились", "по пакету — ответственный; срок, паспорт, деньги — на сверке, при равенстве решает лидер"],
  ["4. Что значит «сделано»", "проверяемый результат из WBS + второй человек", "есть результат пакета, фото в чате, его проверил ещё один человек"],
  ["5. Если кто-то не успевает", "за сколько предупредить, что делает запасной", "предупреждаю за 2 дня; нет связи 3 дня — пакет берёт запасной"]];
Q.forEach(([t, h, e], i) => {
  const y = 130 + i * 150;
  add(rect(30, y, 500, 132, { backgroundColor: BLUE, strokeColor: "#1971c2", label: `${t}\n${h}`, size: 18, align: "left", ...L }));
  cellS(550, y, 1060, 132, i === 0 ? ex(e) : " ", i === 0);
});
cellS(30, 890, 1580, 80, "Согласны (имена всех участников):  ", false);
place();

// ── 3. Журнал проекта ──
zone(1000, "3. Журнал проекта",
  "Одна запись в неделю после сверки: думали / сделали / узнали / дальше. «Работаем» — не статус. Новая неделя — скопируйте колонку (Ctrl+D).");
const R3 = [["Думали", "что собирались\nпо диаграмме Ганта"], ["Сделали", "только готовое\nпо правилу «сделано»"], ["Узнали", "что нового,\nчто пошло не так"], ["Дальше", "что и кто\nна следующей неделе"]];
const ex3 = ["купить компоненты (1.1)", "плата и индикатор пришли; датчик заказан", "магазин отменил заказ датчика, новый\nвезут 10 дней — сработал риск 2",
  "аналитик следит за доставкой; эксперт\nсобирает схему без датчика; коммуникатор\nначинает корпус"];
["Неделя 1  (с ___ по ___)", "Неделя 2  (с ___ по ___)", "Неделя 3  (с ___ по ___)"].forEach((t, k) => add(text(330 + k * 430, 125, t, 19, { ...L, strokeColor: "#1971c2" })));
R3.forEach(([t, h], i) => {
  const y = 165 + i * 200;
  add(rect(30, y, 280, 180, { backgroundColor: BLUE, strokeColor: "#1971c2", label: `${t}\n${h}`, size: 18, ...L }));
  for (let k = 0; k < 3; k++) cellS(330 + k * 430, y, 410, 180, k === 0 ? ex(ex3[i]) : " ", k === 0);
});
place();

// ── 4. План против факта ──
zone(1000, "4. План против факта",
  "Все пакеты, которые по плану должны были начаться к этой неделе. Отклонение — в неделях; «не успели» — не причина.");
const C4 = [["Пакет", 30, 330], ["По плану", 370, 180], ["По факту", 560, 250], ["Откл.", 820, 120], ["Причина", 950, 350], ["Решение", 1310, 300]];
head(C4, 125);
const ex4 = ["1.2 Схема на столе", "неделя 2", "готов в неделю 3", "+1", "ждала датчик (1.1)", "держим план:\nтратим буфер"];
for (let i = 0; i < 6; i++) C4.forEach(([, x, w], j) => cellS(x, 165 + i * 115, w, 100, i === 0 ? ex(ex4[j]) : (j === 3 ? "+ ___" : " "), i === 0,
  i === 0 && j === 0 ? { backgroundColor: RED } : {}));
add(text(30, 870, "Пакет на критическом пути — красный стикер: его отклонение сдвигает весь проект и съедает буфер (резерв времени) перед защитой.", 18, { ...L, strokeColor: "#c92a2a" }));
add(text(30, 905, "Держим план — если отклонение помещается в запас или буфер. Меняем — если нет: урезаем содержание или отдаём часть работы.", 18, { ...L, strokeColor: "#495057" }));
add(text(30, 940, "Любое изменение — в WBS, на диаграмму Ганта и в журнал.", 18, { ...L, strokeColor: "#495057" }));
place();

// ── 5. Что покажем на чекпоинте ──
zone(1000, "5. Что покажем на чекпоинте",
  "Чекпоинт (контрольная точка) 21.11, пять минут. Предъявляем то, что можно взять в руки или прочитать.");
const C5 = [["Результат", "что покажем руками,\nкто принесёт", "схема на макетной плате:\nсухо — индикатор горит.\nПриносит эксперт"],
  ["Обещали", "к этой неделе", "схема, программа\nи калибровка"],
  ["Есть", "на самом деле", "схема готова; программа\nи калибровка не начаты"],
  ["Что следует", "держим или меняем,\nчто именно", "−1 неделя из-за датчика;\nбуфер израсходован;\nдержим план"],
  ["Говорят", "кто что, 5 минут", "лидер — три вопроса;\nэксперт — показ схемы"]];
C5.forEach(([t, h, e], j) => {
  const x = 30 + j * 318;
  add(rect(x, 130, 300, 110, { backgroundColor: BLUE, strokeColor: "#1971c2", label: `${t}\n${h}`, size: 18, ...L }));
  cellS(x, 260, 300, 230, ex(e), true);
  cellS(x, 510, 300, 300, " ", false);
});
add(text(30, 850, "Сводный план — фото в тему команды сразу. Картинка этой доски (Меню → Export image → PNG) и промежуточный результат — на чекпоинт.", 18, { ...L, strokeColor: "#c92a2a" }));
place();

const scene = { type: "excalidraw", version: 2, source: "https://excalidraw.com",
  elements: els, appState: { viewBackgroundColor: "#ffffff", gridSize: null }, files: {} };
const out = process.argv[2] || "zanyatiya/Zanyatie_09_Doska.excalidraw";
fs.writeFileSync(out, JSON.stringify(scene));
console.log("OK", out, els.length, "элементов");
