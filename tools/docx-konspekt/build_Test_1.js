function arrange(opts, pos) {
  const wrong = opts.slice(1);
  const out = [];
  for (let i = 0, w = 0; i < 4; i++) out.push(i === pos ? opts[0] : wrong[w++]);
  return out;
}

const FONT = "Arial";
const run = (t, o = {}) => new TextRun({ text: t, font: FONT, size: o.size || 19, bold: !!o.bold, italics: !!o.italic });
const p = (c, o = {}) => new Paragraph({ children: Array.isArray(c) ? c : [run(c, o)], spacing: { before: o.before || 0, after: o.after ?? 40 }, indent: o.indent, alignment: o.align, keepNext: o.keepNext });
const thin = { style: BorderStyle.SINGLE, size: 4, color: "808080" };
const B = { top: thin, bottom: thin, left: thin, right: thin };
const cell = (t, w, o = {}) => new TableCell({ width: { size: w, type: WidthType.PERCENTAGE }, borders: B, margins: { top: 40, bottom: 40, left: 80, right: 80 }, children: [p([run(t, o)], { after: 0 })] });
const TW = 10106; // ширина текста, twips
const table = (rows, widths) => new Table({
  width: { size: TW, type: WidthType.DXA }, layout: TableLayoutType.FIXED,
  columnWidths: widths.map((w) => Math.round((TW * w) / 100)),
  rows: rows.map((r, i) => new TableRow({ children: r.map((t, j) => new TableCell({ width: { size: Math.round((TW * widths[j]) / 100), type: WidthType.DXA }, borders: B, margins: { top: 30, bottom: 30, left: 80, right: 80 }, children: [p([run(t, { bold: i === 0, size: 19 })], { after: 0, align: j > 0 && widths.length > 2 ? AlignmentType.CENTER : undefined })] })) })),
});

